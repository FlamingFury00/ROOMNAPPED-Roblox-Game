#!/usr/bin/env python3
"""Generate src/shared/Config/AudioIds.luau and the audio table in docs/CONTENT_OWNERSHIP.md from
tools/content/audio_catalog.json.

The catalog lists verified Roblox Creator Store audio (Roblox-owned or Roblox's licensed partner
libraries ProSoundEffects / APM). Each cue has a primary id plus alternates used as runtime fallbacks
when an asset fails to load. Every entry's "source" must be "roblox" or "partner"; the generator refuses
anything else so a community upload can never slip into a release (A10).
"""
import json, os, shutil, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
catalog = json.load(open(os.path.join(root, "tools/content/audio_catalog.json")))
lines = [
    "--!strict",
    "--[[",
    "\tAudioIds: GENERATED by tools/content/gen_audio.py from tools/content/audio_catalog.json - do not edit.",
    "",
    "\tEvery id is a published Roblox Creator Store audio asset owned by Roblox or by Roblox's licensed",
    "\tpartner libraries (ProSoundEffects, APM Music). Alternates are tried in order if the primary fails",
    "\tto load. See docs/CONTENT_OWNERSHIP.md for the provenance record (A10).",
    "]]",
    "",
    "export type AudioId = { id: number, name: string, alternates: { number } }",
    "",
    "local AudioIds: { [string]: AudioId } = {",
]
for key in sorted(catalog):
    entry = catalog[key]
    for item in [entry] + entry.get("alternates", []):
        if item.get("source") not in ("roblox", "partner"):
            sys.exit(f"{key}: {item.get('name')} has source {item.get('source')!r}; only roblox/partner audio ships")
    if entry.get("id") is None:
        continue
    alts = ", ".join(str(a["id"]) for a in entry.get("alternates", []) if a.get("id"))
    name = entry["name"].replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'\t{key} = {{ id = {entry["id"]}, name = "{name}", alternates = {{ {alts} }} }},')
lines.append("}")
lines.append("")
lines.append("return table.freeze(AudioIds)")
out = os.path.join(root, "src/shared/Config/AudioIds.luau")
open(out, "w").write("\n".join(lines) + "\n")
# Match the repository formatting (CI runs `stylua --check`).
stylua = shutil.which("stylua") or "/opt/rbxtools/bin/stylua"
if os.path.exists(stylua):
    subprocess.run([stylua, out], check=True, cwd=root)
else:
    print("warning: stylua not found - run `stylua src/shared/Config/AudioIds.luau` before committing")
print("wrote", out, len(catalog), "cues")

# The provenance table in docs/CONTENT_OWNERSHIP.md, between its generated-block markers.
BEGIN = "<!-- audio-table: generated by tools/content/gen_audio.py, do not edit by hand -->"
END = "<!-- /audio-table -->"


def owner(item):
    return item.get("creator", "").split(" (")[0]


def cell(text):
    return str(text).replace("|", "\\|")


owners = {}
rows = ["| Cue | Asset id | Name | Owner | Alternates |", "| --- | --- | --- | --- | --- |"]
for key in sorted(catalog):
    entry = catalog[key]
    if entry.get("id") is None:
        continue
    owners[owner(entry)] = owners.get(owner(entry), 0) + 1
    alts = ", ".join(str(a["id"]) for a in entry.get("alternates", []) if a.get("id"))
    rows.append(f"| `{key}` | {entry['id']} | {cell(entry['name'])} | {cell(owner(entry))} | {alts} |")
summary = "Owners: " + ", ".join(f"{name} ({count})" for name, count in sorted(owners.items())) + "."
doc = os.path.join(root, "docs/CONTENT_OWNERSHIP.md")
text = open(doc).read()
start, end = text.find(BEGIN), text.find(END)
if start < 0 or end < start:
    sys.exit(f"{doc}: generated-block markers not found")
block = "\n".join([BEGIN, summary, ""] + rows + [END])
open(doc, "w").write(text[:start] + block + text[end + len(END) :])
print("wrote", doc, len(rows) - 2, "rows")
